import {readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync} from 'node:fs';
import {dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {optimizeIcon} from './geometry.mjs';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const check = process.argv.includes('--check');
const catalog = JSON.parse(readFileSync('catalog.json', 'utf8'));
const outputs = new Map();
const header = '// Generated by scripts/generate.mjs. Edit catalog.json.\n';
const reactAttribute = key => key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const manifest = [];
const seen = new Set();
for (const icon of catalog.icons) {
  if (!/^[a-z][a-z0-9-]*$/.test(icon.name) || !/^[A-Z][A-Za-z0-9]*$/.test(icon.symbol) || seen.has(icon.name)) throw new Error(`Invalid or repeated icon ${icon.name}`);
  seen.add(icon.name);
  const {nodes, body: optimizedBody, svg: optimized} = optimizeIcon(icon);
  const geometry = nodes.map(([tag, attrs], index) => {
    const props = Object.fromEntries(Object.entries(attrs).map(([k, v]) => [reactAttribute(k), v]));
    props.vectorEffect = 'var(--bloxwap-icon-vector-effect, none)';
    return `/* @__PURE__ */ createElement(${JSON.stringify(tag)}, ${JSON.stringify({...props, key: index})})`;
  }).join(',\n  ');
  outputs.set(`src/definitions/${icon.name}.ts`, `${header}import type {IconDefinition} from '../core/index.js';\nexport const ${icon.symbol} = ${JSON.stringify({name: icon.name, body: optimizedBody, ...(icon.strokeWidth ? {strokeWidth: icon.strokeWidth} : {})})} as const satisfies IconDefinition;\n`);
  outputs.set(`src/react/${icon.name}.ts`, `${header}import {createElement} from 'react';\nimport {createIcon} from './create-icon.js';\nexport const ${icon.symbol} = /* @__PURE__ */ createIcon(${JSON.stringify(icon.name)}, [\n  ${geometry}\n]${icon.strokeWidth ? `, ${icon.strokeWidth}` : ''});\n`);
  outputs.set(`src/native/${icon.name}.ts`, `${header}import {${icon.symbol} as definition} from '../definitions/${icon.name}.js';\nimport {createIcon} from './create-icon.js';\nexport const ${icon.symbol} = /* @__PURE__ */ createIcon(definition);\n`);
  if (icon.aliasOf) {
    const canonical = catalog.icons.find(entry => entry.name === icon.aliasOf);
    if (!canonical || optimizeIcon(canonical).body !== optimizedBody || (canonical.strokeWidth ?? 2) !== (icon.strokeWidth ?? 2)) throw new Error(`Invalid geometry alias: ${icon.name}`);
    for (const platform of ['react', 'native']) outputs.set(`src/${platform}/${icon.name}.ts`, `${header}export {${canonical.symbol} as ${icon.symbol}} from './${canonical.name}.js';\n`);
  }
  outputs.set(`svg/${icon.name}.svg`, optimized + '\n');
  manifest.push({name: icon.name, symbol: icon.symbol, source: icon.source, strokeWidth: icon.strokeWidth ?? 2, ...(icon.aliasOf ? {aliasOf: icon.aliasOf} : {}),
    sha256: createHash('sha256').update(optimizedBody).digest('hex'), nodes: nodes.length,
    originalNodes: icon.nodes.length, bytes: Buffer.byteLength(optimized)});
}
for (const platform of ['react', 'native']) {
  let index = header + "export type {IconProps, IconComponent} from './create-icon.js';\n";
  for (const icon of catalog.icons) {
    const aliases = Object.entries(catalog.aliases).filter(([, canonical]) => canonical === icon.symbol).map(([alias]) => `${icon.symbol} as ${alias}`);
    index += `export {${[icon.symbol, ...aliases].join(', ')}} from './${icon.name}.js';\n`;
  }
  outputs.set(`src/${platform}/index.ts`, index);
}
outputs.set('manifest.json', JSON.stringify({version: 1, grid: 24, strokeWidth: 2, icons: manifest, aliases: catalog.aliases}, null, 2) + '\n');
let stale = false;
for (const [path, contents] of outputs) {
  if (existsSync(path) && readFileSync(path, 'utf8') === contents) continue;
  if (check) {console.error(`Out of date: ${path}`); stale = true;}
  else {mkdirSync(dirname(path), {recursive: true}); writeFileSync(path, contents);}
}
for (const directory of ['src/definitions', 'src/react', 'src/native', 'svg']) {
  if (!existsSync(directory)) continue;
  for (const name of readdirSync(directory)) {
    const path = `${directory}/${name}`;
    if (!outputs.has(path) && (name.endsWith('.svg') || readFileSync(path, 'utf8').startsWith(header))) {
      if (check) {console.error(`Obsolete generated file: ${path}`); stale = true;}
      else unlinkSync(path);
    }
  }
}
if (stale) process.exitCode = 1;
else console.log(`${check ? 'Verified' : 'Generated'} ${manifest.length} icons for web, native, and SVG.`);
